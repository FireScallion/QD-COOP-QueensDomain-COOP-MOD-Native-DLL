const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "../..");
const scripts = path.join(root, "QDCoop-Direct/mod/Scripts");
const lua = fs.readFileSync(path.join(scripts, "effect_catalog.lua"), "utf8");
const enemyLua = fs.readFileSync(path.join(scripts, "enemy_effect_catalog.lua"), "utf8");
const sections = lua.match(/return \{\["assets"\]=\{(.*?)\},\["projectiles"\]=\{(.*?)\},\["daggers"\]=/);
const enemyAssets = enemyLua.match(/return \{\["assets"\]=\{(.*?)\},\["variables"\]=/);
const playerVariables = lua.match(/\["variables"\]=\{([^{}]*)\}/);
const enemyVariables = enemyLua.match(/\["variables"\]=\{([^{}]*)\}/);
if (!sections || !enemyAssets || !playerVariables || !enemyVariables) throw new Error("Unexpected preview3 effect catalog");

function assetRows(section) {
    return section.split("},{").map(entry => {
        const row = entry.replace(/^\{|\}$/g, "");
        const forward = row.match(/^\["path"\]="([^"]+)",\["kind"\]="([^"]+)"$/);
        if (forward) return forward.slice(1);
        const reverse = row.match(/^\["kind"\]="([^"]+)",\["path"\]="([^"]+)"$/);
        if (reverse) return [reverse[2], reverse[1]];
        throw new Error("Incomplete effect asset row");
    });
}
const assets = assetRows(sections[1]);
const enemy = assetRows(enemyAssets[1]);
const classes = [...sections[2].matchAll(/"([^"]+)"/g)];
if (classes.map(row => row[0]).join(",") !== sections[2]) {
    throw new Error("Incomplete effect catalog section");
}

function table(name, values, prefix = "/") {
    if (!values.length || new Set(values).size !== values.length || values.length > 65534 ||
        values.some(value => !value.startsWith(prefix) || /[\r\n]/.test(value))) {
        throw new Error("Invalid projectile table " + name);
    }
    return [
        `inline constexpr std::array<std::string_view,${values.length}> ${name}{`,
        ...values.map(value => "    " + JSON.stringify(value) + ","),
        "};",
    ];
}
const variablePaths = (section) => [...section[1].matchAll(/"([^"]+)"/g)].map(row => row[1])
    .filter(name => name.startsWith("User."));
const variables = new Map();
for (const name of variablePaths(playerVariables)) {
    if (!variables.has(name.toLowerCase())) variables.set(name.toLowerCase(), name);
}
const playerVariableCount = variables.size;
for (const name of variablePaths(enemyVariables)) {
    if (!variables.has(name.toLowerCase())) variables.set(name.toLowerCase(), name);
}

function resources(name, kind) {
    const paths = rows => rows.filter(row => row[1] === kind).map(row => row[0]).sort();
    const player = paths(assets);
    const playerSet = new Set(player);
    const added = paths(enemy).filter(value => !playerSet.has(value));
    return [`inline constexpr std::size_t player_${name}=${player.length};`, ...table(name, [...player, ...added])];
}

const rows = [
    "// Generated by tools/world/generate-native-projectile-assets.cjs from the preview3 effect catalogs.",
    "#pragma once",
    "#include <algorithm>",
    "#include <array>",
    "#include <cstdint>",
    "#include <string_view>",
    "",
    "namespace qdcoop::projectile::assets {",
    ...table("projectile_classes", classes.map(row => row[1]).sort()),
    ...resources("meshes", "mesh"),
    ...resources("trails", "niagara"),
    ...resources("particles", "particle"),
    `inline constexpr std::size_t player_variables=${playerVariableCount};`,
    ...table("variables", [...variables.values()], "User."),
    "",
    "template<std::size_t Count>",
    "constexpr std::uint16_t id(const std::array<std::string_view,Count>& table,std::string_view path,std::size_t player=Count){",
    "    const auto boundary=table.begin()+player;",
    "    const auto player_id=std::lower_bound(table.begin(),boundary,path);",
    "    if(player_id!=boundary&&*player_id==path)return static_cast<std::uint16_t>(player_id-table.begin()+1);",
    "    const auto enemy_id=std::lower_bound(boundary,table.end(),path);",
    "    return enemy_id!=table.end()&&*enemy_id==path?static_cast<std::uint16_t>(enemy_id-table.begin()+1):0;",
    "}",
    "}",
    "",
];
fs.writeFileSync(path.join(root, "native/include/qdcoop/projectile_assets.hpp"), rows.join("\n"));
