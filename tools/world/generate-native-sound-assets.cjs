const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "../..");
const input = path.join(root, "QDCoop-Direct/mod/Scripts/audio_catalog.lua");
const catalog = fs.readFileSync(input, "utf8");
const sections = catalog.match(/return \{\["sounds"\]=\{(.*?)\},\["attenuations"\]=\{(.*?)\},\["fallbackAttenuation"\]=/);
if (!sections) throw new Error("Unexpected preview3 audio catalog");

const sounds = sections[1].split("},{").map(entry => {
    const row = entry.replace(/^\{|\}$/g, "");
    const fields = [...row.matchAll(/\["([^"]+)"\]=("[^"]+"|true|false|nil|[0-9.eE+-]+)/g)];
    const values = new Map(fields.map(field => [field[1], field[2]]));
    if (fields.map(field => field[0]).join(",") !== row || values.size !== fields.length ||
        !["\"SoundCue\"", "\"SoundWave\""].includes(values.get("kind")) ||
        ![undefined, "true", "false"].includes(values.get("looping"))) {
        throw new Error("Invalid preview3 sound record");
    }
    return [JSON.parse(values.get("path")), values.get("looping") === "true"];
});
const attenuations = JSON.parse("[" + sections[2] + "]");
function validate(values) {
    if (!values.length || values.length > 65534 || new Set(values).size !== values.length ||
        values.some(value => !/^\/(Game|Engine)\/[^\s"]+\.[^\s".]+$/.test(value))) {
        throw new Error("Invalid stock sound asset paths");
    }
}
validate(sounds.map(sound => sound[0]));
validate(attenuations);
sounds.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
attenuations.sort();

const lines = [
    "// Generated by tools/world/generate-native-sound-assets.cjs from preview3 audio_catalog.lua.",
    "#pragma once",
    "#include <algorithm>",
    "#include <array>",
    "#include <cstdint>",
    "#include <string_view>",
    "",
    "namespace qdcoop::sound::assets {",
    "struct Sound {std::string_view path;bool looping;};",
    `inline constexpr std::array<Sound,${sounds.length}> sounds{{`,
    ...sounds.map(([sound, looping]) => `    {${JSON.stringify(sound)},${looping}},`),
    "}};",
    `inline constexpr std::array<std::string_view,${attenuations.length}> attenuations{`,
    ...attenuations.map(attenuation => "    " + JSON.stringify(attenuation) + ","),
    "};",
    "constexpr std::uint16_t sound_id(std::string_view path){",
    "    const auto found=std::lower_bound(sounds.begin(),sounds.end(),path,",
    "        [](const Sound& sound,std::string_view key){return sound.path<key;});",
    "    return found!=sounds.end()&&found->path==path?static_cast<std::uint16_t>(found-sounds.begin()+1):0;",
    "}",
    "constexpr std::uint16_t attenuation_id(std::string_view path){",
    "    const auto found=std::lower_bound(attenuations.begin(),attenuations.end(),path);",
    "    return found!=attenuations.end()&&*found==path?static_cast<std::uint16_t>(found-attenuations.begin()+1):0;",
    "}",
    "}",
    "",
];
const output = path.join(root, "native/include/qdcoop/sound_assets.hpp");
const result = lines.join("\n");
if (process.argv.includes("--check")) {
    if (fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== result) throw new Error("Regenerate sound_assets.hpp");
} else {
    fs.writeFileSync(output, result);
}
console.log(`Native sound assets: ${sounds.length} sounds, ${attenuations.length} attenuation assets`);
